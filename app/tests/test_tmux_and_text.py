def test_score_subsequence_match() -> None:
    assert score("abc", "aXbXc") is not None
    assert score("abc", "acb") is None


def test_score_prefers_consecutive_and_word_start() -> None:
    consecutive = score("cache", "cache layer")
    scattered = score("cache", "c a c h e")
    assert consecutive is not None and scattered is not None
    assert consecutive.score > scattered.score


def test_smart_case() -> None:
    assert score("abc", "ABC") is not None  # 全小写查询 → 不敏感
    assert score("ABC", "abc") is None  # 有大写 → 敏感


def test_empty_query_matches_everything() -> None:
    match = score("", "anything")
    assert match is not None and match.positions == ()


def _entry(title: str, days_ago: int = 0) -> SessionEntry:
    return SessionEntry(
        id=title,
        title=title,
        source=Source.CLAUDE,
        cwd="/home/sean/demo",
        git_branch=None,
        updated_at=datetime.now(tz=UTC) - timedelta(days=days_ago),
        path=f"/tmp/{title}.jsonl",
        size_bytes=1,
    )


def test_rank_keeps_original_order_for_empty_query() -> None:
    entries = [_entry("b"), _entry("a")]
    assert [s.entry.title for s in rank(entries, "")] == ["b", "a"]


def test_rank_filters_and_sorts() -> None:
    entries = [_entry("缓存层"), _entry("cache layer"), _entry("无关")]
    result = rank(entries, "cache")
    assert [s.entry.title for s in result] == ["cache layer"]


def test_rank_breaks_ties_by_recency() -> None:
    entries = [_entry("cache", days_ago=10), _entry("cache", days_ago=1)]
    result = rank(entries, "cache")
    assert result[0].entry.updated_at > result[1].entry.updated_at


def test_haystack_includes_cwd_and_source() -> None:
    entry = _entry("标题")
    assert rank([entry], "demo")
    assert rank([entry], "claude")


