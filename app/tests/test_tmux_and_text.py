def test_zero_width_chars_count_as_zero_columns() -> None:
    """ZWJ / VS16 / 零宽空格 / 肤色修饰符都不占列。

    `unicodedata.combining()` 对它们全返回 0，拦不住 —— 实测
    display_width('👨‍👩‍👧‍👦') 曾算出 11 列（终端实际渲染 2 列），
    导致标题提前截断、pad_display 补位全错。
    """
    assert display_width("‍") == 0  # ZWJ
    assert display_width("​") == 0  # ZWSP
    assert display_width("️") == 0  # VS16
    assert display_width("‎") == 0  # LRM
    assert display_width("👨‍👩‍👧‍👦") == 8  # 4 个双宽 emoji，3 个 ZWJ 不计


def test_truncate_is_single_pass_and_bounded() -> None:
    """截断不该为了「判断超没超」把整条 60KB 消息扫完。"""
    huge = "x" * 200_000
    out = truncate_display(huge, 20)
    assert display_width(out) <= 20
    assert out.endswith("…")


def test_truncate_exact_fit_not_truncated() -> None:
    assert truncate_display("abcde", 5) == "abcde"
    assert truncate_display("中文中", 6) == "中文中"


def test_truncate_boundary_off_by_one() -> None:
    assert truncate_display("abcdef", 5).endswith("…")
    assert display_width(truncate_display("abcdef", 5)) <= 5


def test_clean_title_bounded_on_huge_input() -> None:
    """整条消息可能有 60KB，但正则只该啃有界的前缀。"""
    huge = "开头正文 " + "填充" * 40_000
    out = clean_title(huge, limit=40)
    assert display_width(out) <= 40
    assert out.startswith("开头正文")


def test_pad_display_correct_with_emoji() -> None:
    padded = pad_display("👍", 6)
    assert display_width(padded) == 6


def test_tail_display_keeps_the_end() -> None:
    """输入行截断必须保尾 —— 光标在末尾，截头才看得见正在打的字。"""
    from atm.text import display_width, tail_display

    assert tail_display("abcdefghij", 20) == "abcdefghij"
    out = tail_display("abcdefghij", 6)
    assert out.endswith("ij")
    assert display_width(out) <= 6
    assert tail_display("中文中文中文", 5).endswith("中文")
    assert display_width(tail_display("中文中文中文", 5)) <= 5
    assert tail_display("abc", 0) == ""
    assert display_width(tail_display("abcdef", 1)) <= 1


def test_heading_before_injected_block_is_stripped() -> None:
    """Codex 注入 AGENTS.md 时前面带一行 Markdown 标题，标题行挡住了包装剥离。

    实测后果：那条注入本身成了会话标题，再被噪音规则当机器调用隐藏 ——
    一条 625KB、含 4 条真人消息的会话就这么从列表里消失了。
    """
    from atm.text import strip_wrapper_blocks

    injected = (
        "# AGENTS.md instructions for /home/sean/IdeaProjects/sample-backend\n\n"
        "<INSTRUCTIONS>\n一大堆项目约定……\n</INSTRUCTIONS>"
    )
    assert strip_wrapper_blocks(injected).strip() == ""

    with_real_question = injected + "\n\n现在设置的默认模型是什么"
    assert strip_wrapper_blocks(with_real_question).strip() == "现在设置的默认模型是什么"


def test_plain_heading_is_not_stripped() -> None:
    """单独的标题行是正常内容 —— 只有紧跟着包装标签时才算注入的一部分。"""
    from atm.text import strip_wrapper_blocks

    assert strip_wrapper_blocks("# 我的笔记\n\n这段要保留").startswith("# 我的笔记")
    assert strip_wrapper_blocks("# 标题\n\n普通正文") == "# 标题\n\n普通正文"
