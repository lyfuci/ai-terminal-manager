def test_unknown_unclosed_tag_is_NOT_discarded() -> None:
    """以尖括号 token 开头的**正常提问**不能被整条丢掉。

    之前 strip_wrapper_blocks 见到没闭合的开头标签就 return ""，
    于是 `<div class="x"> 这个标签为什么…` 这类真实提问整条被判成噪音、从列表消失。
    """
    from atm.text import strip_wrapper_blocks

    real = '<div class="box"> 这个标签为什么不居中？'
    assert strip_wrapper_blocks(real) == real
    assert is_junk_prompt(real) is False
    assert "这个标签为什么不居中" in clean_title(real)


