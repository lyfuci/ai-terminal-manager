"""tmux 输出解析 + 文本处理。

`parse_panes` 是纯函数，专门拆出来测 —— tmux 换版本改了输出格式的话，这里会第一个红。
"""

from __future__ import annotations

from datetime import UTC, datetime, timedelta

from atm import tmux
from atm.fuzzy import rank, score
